import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { readFile, mkdir } from 'node:fs/promises';

const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  let paidCalls = 0;
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/api/status', route => route.fulfill({ json: { configured: true, active: false, remaining: null, demoEnabled: true } }));
  await page.route('**/api/start', route => { paidCalls++; return route.fulfill({ status: 500, json: { error: 'test must not generate' } }); });
  await page.goto(process.env.TEST_BASE_URL || 'http://127.0.0.1:5182');
  await page.waitForFunction(() => document.querySelector('#source-name').textContent.includes('Studio'));
  assert.deepEqual(await page.locator('[data-category]').allTextContents(), ['套装', '上衣', '下装', '配饰']);
  assert.equal(await page.locator('#slots .outfit-slot').count(), 4);
  assert.equal(await page.getByRole('button', { name: '移除套装', exact: true }).count(), 1);
  assert.match(await page.locator('#category-help').textContent(), /连衣裙或连体衣/);
  await page.locator('[data-category="top"]').click();
  assert.equal(await page.locator('#wardrobe .garment').count(), 5);
  await page.getByRole('button', { name: '试穿条纹短款外套', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: '移除套装', exact: true }).count(), 0);
  await page.locator('[data-category="bottom"]').click();
  await page.getByRole('button', { name: '试穿直筒原色牛仔裤', exact: true }).click();
  await page.locator('[data-category="accessory"]').click();
  await page.getByRole('button', { name: '试穿白色棒球帽', exact: true }).click();
  await page.locator('[data-category="suit"]').click();
  await page.getByRole('button', { name: '试穿学院风西装裙套装', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: '移除上衣', exact: true }).count(), 0);
  assert.equal(await page.getByRole('button', { name: '移除下装', exact: true }).count(), 0);
  assert.equal(await page.getByRole('button', { name: '移除配饰', exact: true }).count(), 1);
  assert.equal(await page.locator('#garment-upload-title').textContent(), '上传套装图片');
  await page.locator('#garment-file').setInputFiles('public/demo/suit.jpg');
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('已添加suit'));
  assert.equal(await page.getByRole('button', { name: '移除套装', exact: true }).count(), 1);
  const reference = await page.evaluate(async () => {
    const { buildReference, buildPrompt } = await import('/src/media.ts');
    const garments = [{ id: 'suit', name: '套装', category: 'suit', image: '/demo/suit.jpg' }, { id: 'hat', name: '帽子', category: 'accessory', accessory: '帽子', image: '/demo/hat.jpg' }];
    const reference = await buildReference(garments);
    return { layout: reference.layout, bytes: reference.file.size, prompt: buildPrompt(garments, reference.layout) };
  });
  assert.match(reference.layout, /第1列为套装.*第2列为配饰（帽子）/);
  assert.match(reference.prompt, /完整穿上/);
  assert.ok(reference.bytes > 1000);
  const photo = (await readFile('public/demo/jeans.jpg')).toString('base64');
  await page.route('**/api/products/resolve', route => route.fulfill({ json: { title: '链接牛仔裤', sourceUrl: 'https://shop.example/jeans', dataUrl: `data:image/jpeg;base64,${photo}` } }));
  await page.locator('[data-category="bottom"]').click();
  await page.locator('#product-url').fill('https://shop.example/jeans');
  await page.locator('#resolve-link').click();
  await page.waitForFunction(() => document.querySelector('#link-status').textContent.includes('商品已添加'));
  assert.equal(await page.getByRole('button', { name: '移除套装', exact: true }).count(), 0);
  assert.equal(await page.getByRole('button', { name: '移除下装', exact: true }).count(), 1);
  await page.locator('[data-category="suit"]').click();
  await page.getByRole('button', { name: '试穿学院风西装裙套装', exact: true }).click();
  await mkdir('.local/verification', { recursive: true });
  await page.screenshot({ path: '.local/verification/categories-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth) <= 390);
  await page.screenshot({ path: '.local/verification/categories-mobile.png', fullPage: true });
  await page.locator('#source-open').click();
  await page.locator('#coverage').selectOption('half');
  await page.locator('#source-done').click();
  await page.locator('#consent').check();
  await page.locator('#start').click();
  assert.match(await page.locator('#status').textContent(), /套装或下装需要腿部完整入镜/);
  assert.equal(paidCalls, 0);
  assert.deepEqual(errors, []);
  console.log('PASS: four categories, classified images, suit exclusivity with accessories, upload/link categories, reference columns/prompts, half-body validation, mobile layout. Zero paid calls.');
} finally { await browser.close(); }
